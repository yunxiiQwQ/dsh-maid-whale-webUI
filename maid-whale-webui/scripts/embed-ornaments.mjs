import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ids = ['bow', 'whale-tail', 'apron-crest', 'hair-wave', 'bubbles', 'headband-corner', 'ribbon-tab', 'cloud-tide']
const camel = (id) => id.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
const modes = ['light', 'dark']
const art = Object.fromEntries(
  modes.map((mode) => [
    mode,
    Object.fromEntries(
      ids.map((id) => {
        const bytes = readFileSync(resolve(root, 'assets', 'ornaments', mode, `${id}.webp`))
        return [camel(id), `data:image/webp;base64,${bytes.toString('base64')}`]
      }),
    ),
  ]),
)
const names = ids.map(camel)
const source =
  `/* Generated by scripts/embed-ornaments.mjs. */\n` +
  `export const ORNAMENT_IDS = ${JSON.stringify(names)} as const\n` +
  `export type OrnamentId = typeof ORNAMENT_IDS[number]\n` +
  `export type OrnamentMode = 'light' | 'dark'\n` +
  `export const ORNAMENT_ART = ${JSON.stringify(art)} as const\n`

writeFileSync(resolve(root, 'src', 'client', 'ornament-art.generated.ts'), source)
