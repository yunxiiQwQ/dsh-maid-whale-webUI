import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const illustratedBytes = readFileSync(resolve(root, 'assets', 'background', 'cloud-whale-maid.webp'))
const sidebarBytes = readFileSync(resolve(root, 'assets', 'background', 'sidebar-ocean-waves.webp'))
const source =
  `/* Generated by scripts/embed-background.mjs. */\n` +
  `export const ILLUSTRATED_BACKGROUND = ${JSON.stringify(`data:image/webp;base64,${illustratedBytes.toString('base64')}`)} as const\n` +
  `export const SIDEBAR_OCEAN_BACKGROUND = ${JSON.stringify(`data:image/webp;base64,${sidebarBytes.toString('base64')}`)} as const\n`

writeFileSync(resolve(root, 'src', 'client', 'background-art.generated.ts'), source)
